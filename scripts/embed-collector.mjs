// Copies the collector's files into lib/collector-files.ts so the website can
// hand out a ready-to-run download. Runs automatically before `next build`.

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "collector");
const files = {};
for (const name of fs.readdirSync(dir).sort()) {
  if (name === "config.json" || name === "uploaded.json" || name.endsWith(".log") || name.startsWith(".")) continue;
  const full = path.join(dir, name);
  if (!fs.statSync(full).isFile()) continue;
  files[name] = fs.readFileSync(full, "utf8");
}
const out = `// Generated by scripts/embed-collector.mjs. Don't edit; edit the files in collector/ instead.\nexport const COLLECTOR_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
fs.writeFileSync(path.join(root, "lib", "collector-files.ts"), out);
console.log(`Embedded ${Object.keys(files).length} collector files`);
